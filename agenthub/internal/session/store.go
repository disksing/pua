func cloneSession(value Session) Session {
	value.PendingApprovalIDs = append([]string(nil), value.PendingApprovalIDs...)
	value.Source = cloneSource(value.Source)
	value.LaunchEnvironment = cloneEnvironment(value.LaunchEnvironment)
	return value
}

func cloneEnvironment(value map[string]string) map[string]string {
	if value == nil {
		return nil
	}
	cloned := make(map[string]string, len(value))
	for key, entry := range value {
		cloned[key] = entry
	}
	return cloned
}

func cloneSource(value *Source) *Source {
	if value == nil {
		return nil
	}
	cloned := *value
	cloned.Metadata = cloneEnvironment(value.Metadata)
	return &cloned
}

func cloneEvent(value Event) Event {
	value.Data = append(json.RawMessage(nil), value.Data...)
	return value
}

func appendUnique(values []string, value string) []string {
	for _, current := range values {
		if current == value {
			return values
		}
	}
	return append(values, value)
}

func removeString(values []string, value string) []string {
	result := values[:0]
	for _, current := range values {
		if current != value {
			result = append(result, current)
		}
	}
	return result
}
